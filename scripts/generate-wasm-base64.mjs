#!/usr/bin/env node
// Reads the compiled `runway_engine_bg.wasm` binary produced by "npm run build:wasm"
// and converts it into a base64 string, saved into a plain JS module under `src/`.
// Since `runway_engine/pkg` is git-ignored (regenerated locally on every build), this
// committed module is what lets the WASM binary ship with the JS code without also
// having to distribute/serve a separate `.wasm` file - handy for turning this into a library.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');

const wasmPath = path.join(rootDir, 'runway_engine', 'pkg', 'runway_engine_bg.wasm');
const outputPath = path.join(rootDir, 'src', 'runway-engine-wasm.js');

if (!existsSync(wasmPath)) {
  console.error(`[generate-wasm-base64] Could not find "${wasmPath}".`);
  console.error('[generate-wasm-base64] Run "npm run build:wasm" first.');
  process.exit(1);
}

const wasmBytes = readFileSync(wasmPath);
const base64 = wasmBytes.toString('base64');

const fileContent = `// Auto-generated by scripts/generate-wasm-base64.mjs - DO NOT EDIT BY HAND.
// Run "npm run build:engine" to regenerate this file from the compiled WASM binary.
export const RUNWAY_ENGINE_WASM_BASE64 = '${base64}';
`;

writeFileSync(outputPath, fileContent, 'utf-8');

console.log(`[generate-wasm-base64] Encoded ${wasmBytes.length} bytes -> ${base64.length} base64 chars.`);
console.log(`[generate-wasm-base64] Wrote "${outputPath}".`);
